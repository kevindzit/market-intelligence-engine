class RecordingConnection(extensions.connection):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.opened_cursors = []

    def cursor(self, *args, **kwargs):
        cursor = super().cursor(*args, **kwargs)
        self.opened_cursors.append(cursor)
        return cursor


